/** Deduplicate by code (first wins) so seed inserts stay unique. */
export function uniqueDiagnosisCodeSeeds(seeds: Array<[string, string, string]> = DIAGNOSIS_CODE_SEEDS) {
  const seen = new Set<string>();
  return seeds.filter(([, code]) => {
    const key = code.toUpperCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}
